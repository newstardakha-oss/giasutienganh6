export type Gs6WritingUnit = (typeof gs6Writing.units)[number];

export function getUnitWritingData(unitNumberOrId: number | string): Gs6WritingUnit {
  const num =
    typeof unitNumberOrId === 'number'
      ? unitNumberOrId
      : parseInt(String(unitNumberOrId).replace(/\D+/g, ''), 10) || 1;
  return gs6Writing.units.find((u) => u.unit === num) || gs6Writing.units[0];
}

